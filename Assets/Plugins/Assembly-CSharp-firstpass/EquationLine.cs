public class EquationLine
{
	public float A;

	public float CoefficientB;

	public float ConstantC;

	public EquationLine()
	{
		A = 0f;
		CoefficientB = 0f;
		ConstantC = 0f;
	}

	public EquationLine(float a, float AAOIAEJJINO = 0f, float ILHDJDNPFKH = 0f)
	{
		this.A = a;
		this.CoefficientB = AAOIAEJJINO;
		this.ConstantC = ILHDJDNPFKH;
	}
}
